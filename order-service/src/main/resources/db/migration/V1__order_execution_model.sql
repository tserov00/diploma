DROP TABLE IF EXISTS transactions CASCADE;
DROP TABLE IF EXISTS transaction_saga CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS order_status CASCADE;
DROP TABLE IF EXISTS order_type CASCADE;
DROP TABLE IF EXISTS quote_volume_consumption CASCADE;
DROP TABLE IF EXISTS processed_operations CASCADE;
DROP TABLE IF EXISTS customer_portfolios CASCADE;

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    savings_account_id BIGINT NOT NULL,
    currency_id BIGINT NOT NULL,
    side VARCHAR(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    order_type VARCHAR(8) NOT NULL CHECK (order_type IN ('MARKET', 'LIMIT')),
    limit_price NUMERIC(20, 6),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    remaining_quantity INTEGER NOT NULL CHECK (remaining_quantity >= 0 AND remaining_quantity <= quantity),
    reserve_per_unit NUMERIC(20, 6),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'OPEN', 'PROCESSING', 'CANCEL_PENDING', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'REJECTED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK ((order_type = 'LIMIT' AND limit_price IS NOT NULL AND limit_price > 0) OR (order_type = 'MARKET' AND limit_price IS NULL))
);

CREATE INDEX orders_active_security_idx ON orders (security_id, status, created_at);
CREATE INDEX orders_customer_created_idx ON orders (customer_account_id, created_at DESC);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_ref UUID NOT NULL UNIQUE,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    side VARCHAR(4) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    order_type VARCHAR(8) NOT NULL CHECK (order_type IN ('MARKET', 'LIMIT')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    executed_price NUMERIC(20, 6) NOT NULL CHECK (executed_price > 0),
    executed_fee NUMERIC(20, 6) NOT NULL CHECK (executed_fee >= 0),
    market_data_at TIMESTAMPTZ NOT NULL,
    data_source VARCHAR(30) NOT NULL,
    status VARCHAR(12) NOT NULL CHECK (status IN ('PENDING', 'EXECUTED')),
    created_at TIMESTAMPTZ NOT NULL,
    executed_at TIMESTAMPTZ
);

CREATE INDEX transactions_order_idx ON transactions (order_id, created_at);
CREATE INDEX transactions_status_created_idx ON transactions (status, created_at);

CREATE TABLE customer_portfolios (
    customer_account_id BIGINT NOT NULL,
    security_id BIGINT NOT NULL,
    avg_buy_price NUMERIC(20, 8) NOT NULL DEFAULT 0,
    total_quantity INTEGER NOT NULL DEFAULT 0 CHECK (total_quantity >= 0),
    reserved_quantity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0 AND reserved_quantity <= total_quantity),
    avg_sell_price NUMERIC(20, 8) NOT NULL DEFAULT 0,
    sold_quantity INTEGER NOT NULL DEFAULT 0 CHECK (sold_quantity >= 0),
    PRIMARY KEY (customer_account_id, security_id)
);

CREATE TABLE quote_volume_consumption (
    snapshot_key VARCHAR(250) PRIMARY KEY,
    security_id BIGINT NOT NULL,
    ask_used BIGINT NOT NULL DEFAULT 0 CHECK (ask_used >= 0),
    bid_used BIGINT NOT NULL DEFAULT 0 CHECK (bid_used >= 0),
    market_data_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX quote_volume_security_time_idx ON quote_volume_consumption (security_id, market_data_at);

CREATE TABLE processed_operations (
    operation_id UUID PRIMARY KEY
);
